        self.sizeBytes = sizeBytes
        self.recordedSDKRelease = recordedSDKRelease
        self.recordedSDKBuildIdentifier = recordedSDKBuildIdentifier
        self.vtables = vtables
        self.provenance = provenance
    }
}

