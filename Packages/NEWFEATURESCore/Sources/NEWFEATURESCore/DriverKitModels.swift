        release: Int,
        architecture: String = "arm64",
        sdkBuildIdentifier: String,
        classes: [NEWFEATURESSDKClass],
        messages: [NEWFEATURESKernelMessage]
    ) {
        self.schemaVersion = schemaVersion
        self.release = release
        self.architecture = architecture
        self.sdkBuildIdentifier = sdkBuildIdentifier
        self.classes = classes
        self.messages = messages
    }
}

public struct NEWFEATURESVTableEntry: Codable, Hashable, Sendable {
    public let slot: Int
    /// Unqualified address ONLY: may be PAC-signed, relative or cross-image.
    /// NEVER a verified callable/function key without a separate byte witness.
    public let targetAddress: UInt64
    public let symbolName: String?
    public init(slot: Int, targetAddress: UInt64, symbolName: String? = nil) {
        self.slot = slot
        self.targetAddress = targetAddress
        self.symbolName = symbolName
    }
}

public struct NEWFEATURESObservedVTable: Codable, Hashable, Sendable {
    public let address: UInt64
