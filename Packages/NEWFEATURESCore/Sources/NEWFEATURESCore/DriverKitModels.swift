import Foundation

public struct NEWFEATURESDriverKitField: Codable, Hashable, Sendable {
    public let name: String
    public let typeName: String
    public let offsetBytes: UInt64
    public let sizeBytes: UInt64

    public init(name: String, typeName: String, offsetBytes: UInt64, sizeBytes: UInt64) {
        self.name = name
        self.typeName = typeName
        self.offsetBytes = offsetBytes
        self.sizeBytes = sizeBytes
    }
}

/// All SDK declarations here must derive from locally installed Apple SDK headers.
/// No private class, field or message name is invented by the core.
public struct NEWFEATURESSDKClass: Codable, Hashable, Sendable {
    public let name: String
    public let parentName: String?
    public let sizeBytes: UInt64
    public let fields: [NEWFEATURESDriverKitField]

    public init(name: String, parentName: String?, sizeBytes: UInt64, fields: [NEWFEATURESDriverKitField]) {
        self.name = name
        self.parentName = parentName
        self.sizeBytes = sizeBytes
        self.fields = fields
    }
}

public struct NEWFEATURESKernelMessage: Codable, Hashable, Sendable {
    public let id: UInt64
    public let name: String
    public init(id: UInt64, name: String) { self.id = id; self.name = name }
}

public struct NEWFEATURESDriverKitCatalog: Codable, Sendable {
    public let schemaVersion: Int
    public let release: Int
    public let architecture: String
    public let sdkBuildIdentifier: String
