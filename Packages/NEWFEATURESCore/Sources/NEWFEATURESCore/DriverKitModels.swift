/// These expected values MUST be loaded from an independently trusted local
/// installed-SDK corpus allowlist, never copied from an arbitrary JSON input.
/// Digest is SHA-256 of the EXACT Python canonical UTF-8 catalog wire,
/// including the trailing LF. Header-tree verification is performed by the
/// app's trusted installed-SDK importer, not independently by this type.
public struct NEWFEATURESTrustedSDKAdmission: Sendable {
    public let release: Int
    public let buildIdentifier: String
    public let pinnedCatalogSHA256: String
    public let sourceHeaderTreeSHA256: String

    public init(
        release: Int,
        buildIdentifier: String,
        pinnedCatalogSHA256: String,
        sourceHeaderTreeSHA256: String
    ) {
        self.release = release
        self.buildIdentifier = buildIdentifier
        self.pinnedCatalogSHA256 = pinnedCatalogSHA256
        self.sourceHeaderTreeSHA256 = sourceHeaderTreeSHA256
    }
}

/// Admission and message indexing occur ONCE per trusted catalog, not for
/// each callsite. Constructor is internal: only the validating factory creates
/// a usable catalog index.
public struct NEWFEATURESAdmittedDriverKitCatalog: Sendable {
    public let release: Int
    public let architecture: String
    public let buildIdentifier: String
    public let pinnedCatalogSHA256: String
    let messageNames: [UInt64: String]

    init(catalog: NEWFEATURESDriverKitCatalog, digest: String) {
        release = catalog.release
        architecture = catalog.architecture
        buildIdentifier = catalog.sdkBuildIdentifier
        pinnedCatalogSHA256 = digest
        messageNames = Dictionary(uniqueKeysWithValues: catalog.messages.map { ($0.id, $0.name) })
    }
}

