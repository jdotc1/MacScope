import Foundation

enum RegenerationError: Error, LocalizedError, Equatable {
    case invalidInput(String)
    case invalidPath(String)
    case destinationExists
    case toolFailed(String)

    var errorDescription: String? {
        switch self {
        case .invalidInput(let reason): "regeneration-invalid-input: \(reason)"
        case .invalidPath(let reason): "regeneration-invalid-path: \(reason)"
        case .destinationExists: "regeneration-destination-exists: existing output was preserved"
        case .toolFailed(let reason): "regeneration-tool-failed: \(reason)"
        }
    }
}

enum RegenerationLanguage: String, Codable, Sendable { case objc, swift, c, unknown }
enum RegenerationFunctionState: String, Codable, Sendable { case stub, filled, compiles, accepted, external }

struct RegenerationImageIdentity: Codable, Equatable, Sendable {
    let imageSlot: Int
    let selectedSliceIndex: Int?
    let architecture: String
    let selectedSliceSHA256: String
    let analysisFingerprintSHA256: String
}

/// Identity is supplied by the image-qualified snapshot adapter, never generated by a renderer.
struct RegenerationFunctionInput: Equatable, Sendable {
    var functionUUID: UUID
    var address: UInt64
    var endAddress: UInt64
    var name: String
    var language: RegenerationLanguage
    var recoveredDeclaration: String?
    var cSignature: RegenerationCSignature?
}

/// A declaration recovered with explicit provenance. Unsupported types use an opaque stub instead.
struct RegenerationCSignature: Equatable, Sendable {
    var returnType: String
    var parameterTypes: [String]
    var provenance: String

    var canRender: Bool {
        let scalar: Set<String> = ["void", "char", "signed char", "unsigned char", "short", "unsigned short",
            "int", "unsigned int", "long", "unsigned long", "long long", "unsigned long long", "float", "double", "_Bool"]
        return !provenance.isEmpty && scalar.contains(returnType)
            && parameterTypes.allSatisfy { $0 != "void" && scalar.contains($0) }
    }
}

struct RegenerationProjectInput: Sendable {
    var applicationName: String
    var image: RegenerationImageIdentity
    var functions: [RegenerationFunctionInput]
    var originalDeploymentTarget: String?
    var dependentLibraries: [String]
    var referenceFiles: [String: Data]
    var diagnostics: [String]
    var nominalTypes: [RegenerationNominalTypeInput] = []
}

enum RegenerationNominalKind: String, Sendable { case `class`, `struct`, `enum`, unknown }

struct RegenerationNominalTypeInput: Sendable {
    struct Field: Sendable {
        let name: String
        let recoveredType: String?
        let mutable: Bool
    }
    let name: String
    let module: String?
    let language: RegenerationLanguage
    let kind: RegenerationNominalKind
    let fields: [Field]
}

struct RegenerationFunctionRecord: Codable, Equatable, Sendable {
    struct Coordinate: Codable, Equatable, Sendable {
        let imageSlot: Int
        let selectedSliceIndex: Int?
        let imageSHA256: String
        /// Hex text avoids JSON numeric precision loss for 64-bit addresses.
        let address: String
        let endAddressExclusive: String
    }
    let imageQualifiedAddress: Coordinate
    let functionUUID: UUID
    let name: String
    let language: RegenerationLanguage
    let stubFile: String
    let stubLine: Int
    let state: RegenerationFunctionState
    let diagnostics: [String]
    var cBody: RegenerationCBodyProvenance? = nil
    /// Caller declaration only; never establishes function ownership.
    var dependencyId: String? = nil
}

struct RegenerationResourceProvenance: Codable, Equatable, Sendable {
    let captureBasis: String
    let imageBinding: String
    static let currentBundle = Self(captureBasis: "currentBundlePath", imageBinding: "unassessed")
    static let diagnostic = "Resources and bundle Info.plist are current observations at the supplied bundle path. They are not proven to belong to the earlier captured image; a same-path bundle may have been replaced. Successful round-trip comparisons certify only the currently read resources, not their association with the captured image or function equivalence."
}

struct RegenerationDependencyInventoryCapability: Codable, Equatable, Sendable {
    let path: String
    let coverage: String
    let liveBundleObservations: String
}

struct RegenerationCapabilities: Codable, Equatable, Sendable {
    let dependencyInventory: RegenerationDependencyInventoryCapability
}

struct RegenerationManifest: Codable, Equatable, Sendable {
    let schemaVersion: Int
    let applicationName: String
    let image: RegenerationImageIdentity
    let originalDeploymentTarget: String?
    let deploymentTarget: String
    let dependentLibraries: [String]
    let functions: [RegenerationFunctionRecord]
    let resources: [ResourceRoundTripRecord]
    let resourceProvenance: RegenerationResourceProvenance
    let capabilities: RegenerationCapabilities?
    let diagnostics: [String]
}

struct RegenerationRenderedProject: Sendable {
    var files: [String: Data]
    let manifest: RegenerationManifest
    let buildResources: [String]
}

enum RegenerationEncoding {
    static func json<T: Encodable>(_ value: T) throws -> Data {
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.sortedKeys, .prettyPrinted, .withoutEscapingSlashes]
        return try encoder.encode(value) + Data([10])
    }

    static func relativePath(_ value: String) -> Bool {
        !value.isEmpty && !value.hasPrefix("/") && !value.contains("\\")
            && !value.unicodeScalars.contains { $0.value < 32 || $0.value == 127 }
            && value.split(separator: "/", omittingEmptySubsequences: false).allSatisfy {
                !$0.isEmpty && $0 != "." && $0 != ".."
            }
    }

    /// Recovered text is data, even when it contains preprocessor directives or Unicode newlines.
    static func annotation(_ value: String) -> String {
        value.unicodeScalars.map { scalar in
            if (32...126).contains(scalar.value), scalar != "\\" { return String(scalar) }
            return "\\u{\(String(scalar.value, radix: 16))}"
        }.joined()
    }

    static func identifier(_ value: String) -> String {
        let scalars = value.unicodeScalars.prefix(64).map { scalar -> String in
            ((65...90).contains(scalar.value) || (97...122).contains(scalar.value)
             || (48...57).contains(scalar.value) || scalar == "_") ? String(scalar) : "_"
        }.joined()
        guard let first = scalars.utf8.first else { return "RecoveredApp" }
        return (48...57).contains(first) ? "Recovered_" + scalars : scalars
    }

    static func address(_ value: UInt64) -> String { String(format: "0x%016llx", value) }
}
